function [ x ] = deter( A )
% Функция считает определитель матрицы
% A - Матрица

x = 0; % Значение определителя

if size(A,1) == 2
    x = A(1,1)*A(2,2) - A(1,2)*A(2,1); % Если размер 2x2 то считает определитель через главную и побочную диагональ
end

for j=1:size(A,1)
    minor = A;
    minor(1,:) = [];
    minor(:,j) = [];
    x = x + A(1,j)*(-1)^(1+j)*deter(minor); % Считает оперделитель разложением по первой строке
end

end